function dimensionsFor(rule) {
  const body = JSON.stringify([rule.必要条件, rule.触发动作, rule.目标状态或可观察结果, rule.用例设计]);
  const dimensions = new Set(["可观察结果"]);
  if (rule.可生成正式用例 && rule.用例设计?.用例类型 !== "异常用例") dimensions.add("正常主流程");
  if (/空|长度|上限|下限|最多|最少|边界|\d+\s*(?:位|人|分钟|小时|个)|非法|有效值/u.test(body)) dimensions.add("输入边界");
  if (/失败|不足|不可|不能|不显示|不生成|错误|无效|拒绝|拦截|封禁|下架|超时/u.test(body)) dimensions.add("异常/失败");
  if (/取消|关闭|中断|退出/u.test(body)) dimensions.add("中断/取消");
  if (/重试|恢复|解除|重新/u.test(body)) dimensions.add("重试/恢复");
  if (/重复|再次|连续|两次|幂等|不重复/u.test(body)) dimensions.add("重复操作");
  if (/权限|角色|游客|巡房|房管|运营账号|拉黑/u.test(body)) dimensions.add("权限差异");
  if (/状态|切换|更新|失效|生效|开始|结束|加入|退出|禁言|踢出/u.test(body)) dimensions.add("状态切换");
  if (/余额|记录|列表|榜|收益|贡献|同步|历史|快照|数据|金币|场次/u.test(body)) dimensions.add("数据一致性");
  if (/重新进入|再次进入|刷新|返回|跨场次|下一场|后续登录|保留/u.test(body)) dimensions.add("重新进入/刷新状态保持");
  return [...dimensions];
}

function buildCoverageReview(group, atomicRules) {
  const isolated = atomicRules.every((rule) => !rule.可生成正式用例);
  if (isolated) {
    const question = `Q-${atomicRules[0].稳定规则标识.slice(-3)}`;
    const pendingDimensions = new Set([
      "可观察结果",
      ...(Object.values(pendingCoverage).find((item) => item.问题 === question)?.维度 || []),
    ]);
    return COVERAGE_DIMENSIONS.map((dimension) => pendingDimensions.has(dimension)
      ? { 维度: dimension, 状态: "待确认", 原因: `${question} 缺少确定规则，已隔离且不影响其他明确分支` }
      : { 维度: dimension, 状态: "不适用", 原因: "当前待确认事项未显示该条件会形成另一确定结果" });
  }
  const covered = new Set(atomicRules.flatMap(dimensionsFor));
  const roles = new Set(atomicRules.map((rule) => rule.执行角色));
  if (roles.size > 1) covered.add("用户角色");
  if (new Set(atomicRules.map((rule) => rule.来源状态)).size > 1) covered.add("前置状态");
  const pending = pendingCoverage[group];
  return COVERAGE_DIMENSIONS.map((dimension) => {
    if (covered.has(dimension)) return { 维度: dimension, 状态: "已覆盖", 原因: `存在 ${atomicRules.filter((rule) => dimensionsFor(rule).includes(dimension)).length || atomicRules.length} 个结果会变化的证据化分支` };
    if (pending?.维度.includes(dimension)) return { 维度: dimension, 状态: "待确认", 原因: `${pending.问题} 缺少确定规则，其他明确分支继续生成` };
    return { 维度: dimension, 状态: "不适用", 原因: "递归关联证据未显示该条件会改变当前规则结果" };
  });
}

function groupRules(atomicRules) {
  const groups = new Map();
  for (const rule of atomicRules) {
    const key = rule.可生成正式用例 ? groupName(rule.功能结构) : rule.稳定规则标识;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(rule);
  }
  return [...groups].map(([group, rules]) => {
    const parent = structuredClone(rules[0]);
    parent.稳定规则标识 = `BR-LIVE-GROUP-${sha256Buffer(group).slice(0, 10).toUpperCase()}`;
    parent.业务对象 = ruleGroupLabel(group);
    parent.覆盖判断 = buildCoverageReview(group, rules);
    parent.场景分支 = rules.map((rule, index) => ({
      分支标识: `${parent.稳定规则标识}-B${String(index + 1).padStart(2, "0")}`,
      变化维度: dimensionsFor(rule),
      有效条件: rule.必要条件.length ? rule.必要条件 : ["当前证据缺少可生成正式用例的确定结果"],
      拆分原因: rule.可生成正式用例 ? "该条件变化会改变页面表现、业务结果或后续状态" : "缺少确定结果，分支已隔离为需求待确认",
      原子规则: rule,
    }));
    parent.设计复核 = { 状态: "通过", 说明: "父规则及场景分支已逐条核对当前证据", 设计SHA256: ruleDesignHash(parent) };
    return parent;
  });
}

function ruleGroupLabel(group) {
  return group.startsWith("BR-LIVE-PENDING-") ? "待确认规则" : `${group}业务分支`;
}

