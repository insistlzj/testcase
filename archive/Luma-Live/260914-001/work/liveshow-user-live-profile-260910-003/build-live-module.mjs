function reviewCases(cases) {
  const compactList = (items) => [...items].map((item) => String(item).trim()).sort();
  const exactGroups = new Map();
  const scenarioGroups = new Map();
  for (const item of cases) {
    const exactKey = JSON.stringify([item.功能结构, compactList(item.前置条件), item.操作步骤, item.预期结果]);
    if (!exactGroups.has(exactKey)) exactGroups.set(exactKey, []);
    exactGroups.get(exactKey).push(item.用例编号);
    const scenarioKey = JSON.stringify([item.功能结构, item.用例描述, item.操作步骤]);
    if (!scenarioGroups.has(scenarioKey)) scenarioGroups.set(scenarioKey, []);
    scenarioGroups.get(scenarioKey).push(item);
  }
  const exact = [...exactGroups.values()].filter((ids) => ids.length > 1);
  const subsets = [];
  const conflicts = [];
  for (const group of scenarioGroups.values()) {
    for (let i = 0; i < group.length; i += 1) {
      for (let j = i + 1; j < group.length; j += 1) {
        const left = group[i], right = group[j];
        const leftPre = new Set(compactList(left.前置条件));
        const rightPre = new Set(compactList(right.前置条件));
        const sameResult = JSON.stringify(left.预期结果) === JSON.stringify(right.预期结果);
        const isSubset = [...leftPre].every((value) => rightPre.has(value)) || [...rightPre].every((value) => leftPre.has(value));
        if (sameResult && isSubset) subsets.push([left.用例编号, right.用例编号]);
        if (!sameResult && JSON.stringify([...leftPre].sort()) === JSON.stringify([...rightPre].sort())) {
          conflicts.push([left.用例编号, right.用例编号]);
        }
      }
    }
  }
  return { 完全重复: exact, 条件子集重复: subsets, 预期冲突: conflicts };
}

async function buildInventory() {
  const files = (await listFiles(abs(project))).sort();
  const rows = [];
  for (const file of files) {
    const relative = path.relative(root, file).split(path.sep).join("/");
    const stat = await fs.stat(file);
    rows.push({ 路径: relative, 大小: stat.size, 修改时间: stat.mtime.toISOString(), "SHA-256": sha256Buffer(await fs.readFile(file)) });
  }
  return rows;
}

