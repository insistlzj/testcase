function sourceFor(spec) {
  if (spec.key.startsWith("系统概要")) {
    if (!texts[summaryPath].includes(spec.needle)) throw new Error(`系统概要未命中：${spec.needle}`);
    return { 路径: summaryPath, "SHA-256": hashes[summaryPath], 位置: spec.key, 证明内容: spec.result, 原文: spec.needle };
  }
  const page = annotations[spec.key];
  if (!page) throw new Error(`缺少结构化批注：${spec.key}`);
  const pageText = page.sections.flatMap((section) => section.d).join("\n");
  if (!pageText.includes(spec.needle)) throw new Error(`${spec.key} 未命中：${spec.needle}`);
  if (!texts[annPath].includes(spec.needle)) throw new Error(`批注源文件未命中：${spec.needle}`);
  return { 路径: annPath, "SHA-256": hashes[annPath], 位置: `${spec.key} 结构化批注`, 证明内容: spec.result, 原文: spec.needle };
}

