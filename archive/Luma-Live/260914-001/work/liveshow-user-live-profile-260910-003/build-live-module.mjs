function projectFingerprint(inventory) {
  const prefix = `${project}/`;
  return sha256Buffer(inventory.map((item) => ({ path: item.路径.startsWith(prefix) ? item.路径.slice(prefix.length) : item.路径, hash: item["SHA-256"] }))
    .sort((left, right) => left.path.localeCompare(right.path, "zh-CN"))
    .map((item) => `${item.path}|${item.hash}`).join("\n"));
}

