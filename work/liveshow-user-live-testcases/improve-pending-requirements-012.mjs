function treeOrder(items) {
  const children = new Map();
  for (const item of items) {
    const key = item.父问题编号 || "";
    if (!children.has(key)) children.set(key, []);
    children.get(key).push(item);
  }
  children.forEach((records) => records.sort((left, right) => left.问题编号.localeCompare(right.问题编号)));
  const ordered = [];
  const visit = (item) => {
    ordered.push(item);
    for (const child of children.get(item.问题编号) ?? []) visit(child);
  };
  for (const root of children.get("") ?? []) visit(root);
  assert.equal(ordered.length, items.length, `需求组 ${items[0]?.需求组编号} 存在孤儿或循环关系`);
  return ordered;
}

questions = [...groups.entries()]
