function splitImpact(values) {
  const existing = [];
  const pending = [];
  for (const value of values ?? []) {
    const parts = String(value).split("、").map((part) => part.trim()).filter(Boolean);
    for (const part of parts) {
      if (/^[A-Z][A-Z0-9]*-\d{3}(?:\s+至\s+[A-Z][A-Z0-9]*-\d{3})?$/.test(part)) existing.push(part);
      else pending.push(part);
    }
  }
  return { existing: [...new Set(existing)], pending: [...new Set(pending)] };
}

