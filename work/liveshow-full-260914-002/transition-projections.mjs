export function projectTransition(d){
 const eligible=new Set(transitions.filter(t=>t.操作端===d.end||t.观察端.includes(d.end)).map(t=>t.状态转换标识));
 const match=links.find(([id,label])=>eligible.has('TR-'+id)&&label.test(d.label));
 return match?'TR-'+match[0]:'';
}
